#!/usr/bin/env node
/**
 * PreToolUse hook. Hooks run even under --dangerously-skip-permissions, so this
 * is the guardrail that survives when the permission system is switched off.
 *
 * Blocks, for agent worktrees (../el-<agent>):
 *   - any command that touches the REMOTE Supabase project, pushes git, or changes deps
 *   - Edit/Write outside the agent's owned paths (CONTRACTS §0)
 *   - shell writes (>, >>, tee, sed -i) into a path the agent does not own
 *
 * The lead checkout (einfachlernen/) gets the remote-command checks only.
 * Exit 2 blocks the call and shows `reason` to the agent.
 *
 * Lead-owned — agents do not edit this file.
 */
import {
  agentFromDir,
  ownershipViolation,
  FORBIDDEN_COMMANDS,
  LEAD_ONLY_COMMANDS,
} from './ownership.mjs';

const chunks = [];
for await (const c of process.stdin) chunks.push(c);

let payload;
try {
  payload = JSON.parse(Buffer.concat(chunks).toString('utf8') || '{}');
} catch {
  process.exit(0); // never break the session on a parse failure
}

const tool = payload.tool_name || '';
const input = payload.tool_input || {};
const cwd = payload.cwd || process.cwd();
const root = process.env.CLAUDE_PROJECT_DIR || cwd;
const agent = agentFromDir(root);

function block(reason) {
  process.stderr.write(`BLOCKED by scripts/agents/guard.mjs: ${reason}\n`);
  process.exit(2);
}

/**
 * Strip the parts of a shell command that are data, not instructions: heredoc
 * bodies and quoted literals. Without this, `git commit -m "… git push …"` and
 * any heredoc that documents a forbidden command get blocked — which agents
 * writing status files and commit messages would hit constantly.
 */
function commandSkeleton(cmd) {
  let s = cmd;
  // heredocs: <<EOF … EOF / <<'EOF' … EOF / <<-"EOF" … EOF
  s = s.replace(/<<-?\s*(["']?)([A-Za-z_][\w-]*)\1[\s\S]*?^\s*\2\s*$/gm, '<<HEREDOC');
  // an unterminated heredoc (the body runs to the end of the string)
  s = s.replace(/<<-?\s*(["']?)([A-Za-z_][\w-]*)\1[\s\S]*$/, '<<HEREDOC');
  // quoted literals
  s = s.replace(/'[^']*'/g, "''").replace(/"(?:\\.|[^"\\])*"/g, '""');
  return s;
}

// ── 1. Commands that reach the remote project, GitHub, or package.json ──
if (tool === 'Bash') {
  const cmd = String(input.command || '');
  const skeleton = commandSkeleton(cmd);
  for (const { re, why } of FORBIDDEN_COMMANDS) {
    if (re.test(skeleton)) {
      block(
        `\`${cmd.slice(0, 120)}\` ${why}. ` +
          `Local Supabase only (start / db reset / functions serve). ` +
          `If you need this, write it in docs/agents/status/${agent ?? '<agent>'}.md and continue.`,
      );
    }
  }
}

// Everything below applies only inside an agent worktree; the lead checkout
// owns package.json and does the merging, so these are its prerogative.
if (!agent) process.exit(0);

// ── 1b. Lead-only commands ──
if (tool === 'Bash') {
  const skeleton = commandSkeleton(String(input.command || ''));
  for (const { re, why } of LEAD_ONLY_COMMANDS) {
    if (re.test(skeleton)) {
      block(
        `\`${String(input.command).slice(0, 120)}\` ${why}. ` +
          `You are the ${agent} agent; write the request in docs/agents/status/${agent}.md and continue.`,
      );
    }
  }
}

// ── 2. Direct file edits ──
if (['Edit', 'Write', 'MultiEdit', 'NotebookEdit'].includes(tool)) {
  const abs = String(input.file_path || input.notebook_path || '');
  if (abs.startsWith(root)) {
    const rel = abs.slice(root.length).replace(/^\//, '');
    const violation = ownershipViolation(agent, rel);
    if (violation) {
      block(
        `${violation}. You are the ${agent} agent (CLAUDE.md → File ownership). ` +
          `Write the request under "Contract change requests" in ` +
          `docs/agents/status/${agent}.md and keep working against the current contract.`,
      );
    }
  }
}

// ── 3. Shell writes that would sidestep the Edit tool ──
if (tool === 'Bash') {
  const cmd = commandSkeleton(String(input.command || ''));
  const targets = new Set();
  // `> path`, `>> path`, `tee path`, `sed -i … path`, `cp/mv … path`
  for (const re of [
    /(?:^|[^>])>>?\s*(["']?)([\w./@()\[\]-]+)\1/g,
    /\btee\s+(?:-a\s+)?(["']?)([\w./@()\[\]-]+)\1/g,
    /\bsed\s+-i\b[^|;&]*?(["']?)([\w./@()\[\]-]+\.\w+)\1\s*(?:$|[|;&])/g,
    /\b(?:cp|mv)\s+[^|;&]*?\s(["']?)([\w./@()\[\]-]+)\1\s*(?:$|[|;&])/g,
  ]) {
    for (const m of cmd.matchAll(re)) targets.add(m[2]);
  }
  for (const t of targets) {
    if (t.startsWith('/') || t.startsWith('..') || t.startsWith('~')) continue; // outside the repo: not ours to police
    if (/^\/dev\/null$/.test(t)) continue;
    const violation = ownershipViolation(agent, t);
    if (violation) {
      block(
        `this command writes to ${t}, and ${violation}. You are the ${agent} agent. ` +
          `Use the Edit tool inside your own paths; request the change in ` +
          `docs/agents/status/${agent}.md otherwise.`,
      );
    }
  }
}

process.exit(0);
