#!/usr/bin/env node
/**
 * Stage 08 — emit the seed SQL.
 *
 *   node scripts/content/08_seed.mjs
 *
 * Writes supabase/seeds/010_de_words_v3.sql as INSERT … ON CONFLICT (id) DO
 * UPDATE, so `supabase db reset` is idempotent and a re-run updates in place.
 *
 * Ids keep the existing `de-{level}-{code}-{seq}` shape, and the 168 rows that
 * already exist keep their ids: a learner's word_progress points at them, so
 * renumbering would orphan real progress.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, STAGE, stage } from './_lib.mjs';

const SEED = join(ROOT, 'supabase', 'seeds', '010_de_words_v3.sql');

const THEMA_CODE = {
  'Alltag': 'al',
  'Arbeit und Beruf': 'ab',
  'Bildung und Ausbildung': 'bi',
  'Essen und Trinken': 'es',
  'Gesundheit': 'ge',
  'Reisen und Verkehr': 'rv',
  'Wohnen': 'wo',
  'Gesellschaft und Umwelt': 'gu',
};

const q = (v) =>
  v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`;

await stage('08_seed', async () => {
  const rows = readJsonl(join(STAGE, '07_validated.jsonl'));

  // Existing ids, keyed by lower(german), so they stay stable.
  let existing = new Map();
  try {
    const tsv = execFileSync(
      'docker',
      ['exec', 'supabase_db_einfachlernen', 'psql', '-U', 'postgres', '-t', '-A', '-F', '\t', '-c',
       'select lower(german), id from de_words'],
      { encoding: 'utf8' },
    ).trim();
    existing = new Map(tsv.split('\n').filter(Boolean).map((l) => l.split('\t')));
    console.log(`  ${existing.size} existing ids will be preserved`);
  } catch {
    console.log('  local DB unavailable — every row gets a fresh id');
  }

  const seqByPrefix = new Map();
  const seen = new Set();
  const sqlRows = [];

  for (const r of rows) {
    const key = r.lemma.toLowerCase();
    if (seen.has(key)) continue; // lemma_key is unique in the catalogue
    seen.add(key);

    let id = existing.get(key);
    if (!id) {
      const code = THEMA_CODE[r.thema] ?? 'al';
      const prefix = `de-${r.level.toLowerCase()}-${code}`;
      const n = (seqByPrefix.get(prefix) ?? 0) + 1;
      seqByPrefix.set(prefix, n);
      id = `${prefix}-${String(n).padStart(4, '0')}`;
    }

    sqlRows.push(
      `  (${[
        q(id), q(r.level), q(r.thema), q(r.word_type), q(r.lemma), q(r.article), q(r.english),
        q(r.example_de), q(r.example_en), `'${JSON.stringify(r.forms ?? {}).replace(/'/g, "''")}'::jsonb`,
        q(r.thema), String(r.frequency_rank ?? 'NULL'), q(r.level_source),
        String(r.level_confidence ?? 'NULL'), q(r.review_status),
        q('leipzig+opensubtitles+ai'),
      ].join(', ')})`,
    );
  }

  const sql = `-- 010_de_words_v3.sql — generated by scripts/content/08_seed.mjs
-- Do not hand-edit: re-run the pipeline and regenerate.
--
-- Source: Leipzig Corpora Collection (written frequency) + OpenSubtitles
-- (spoken frequency), levels derived by the stage 04 ensemble, entries
-- generated and validated in stages 06-07. No licensed wordlist (PRD D12).
--
-- ${sqlRows.length} rows. Existing ids preserved so word_progress keeps pointing
-- at the right cards.

BEGIN;

INSERT INTO public.de_words
  (id, level, category, word_type, german, article, english,
   example_de, example_en, forms, thema, frequency_rank, level_source,
   level_confidence, review_status, source)
VALUES
${sqlRows.join(',\n')}
ON CONFLICT (id) DO UPDATE SET
  level            = EXCLUDED.level,
  category         = EXCLUDED.category,
  word_type        = EXCLUDED.word_type,
  article          = EXCLUDED.article,
  english          = EXCLUDED.english,
  example_de       = EXCLUDED.example_de,
  example_en       = EXCLUDED.example_en,
  forms            = EXCLUDED.forms,
  thema            = EXCLUDED.thema,
  frequency_rank   = EXCLUDED.frequency_rank,
  level_source     = EXCLUDED.level_source,
  level_confidence = EXCLUDED.level_confidence,
  review_status    = EXCLUDED.review_status,
  source           = EXCLUDED.source,
  updated_at       = now();

COMMIT;
`;

  mkdirSync(join(ROOT, 'supabase', 'seeds'), { recursive: true });
  writeFileSync(SEED, sql);
  console.log(`  wrote ${sqlRows.length} rows → supabase/seeds/010_de_words_v3.sql (${(sql.length / 1024).toFixed(0)} KB)`);
  return { in: rows.length, out: sqlRows.length };
});

function readJsonl(p) {
  if (!existsSync(p)) throw new Error(`missing ${p} — run stage 07 first`);
  return readFileSync(p, 'utf8').split('\n').filter(Boolean).map((l) => JSON.parse(l));
}
